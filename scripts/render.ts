import {
  type ColorRef,
  type Scale,
  type ScaleName,
  colorScaleNames,
  palette,
  resolve,
  roleBindings,
  roleScaleNames,
  steps
} from "#/src/palette.ts";
import { type SemanticTokenName, semanticTokens } from "#/src/semantic.ts";
import { packageName } from "./project.ts";

/** The files the build writes into dist/; package.json exports each one. */
export const outputFiles = {
  index: "index.css",
  palette: "palette.css",
  semantic: "semantic.css",
  tokens: "tokens.json"
} as const;

// Custom property prefixes: --palette-* for Layer 1, --color-* for Layer 2
const palettePrefix = "--palette-";
const semanticPrefix = "--color-";

const banner = `/* Generated by ${packageName}. Edit the package's source, not this file. */`;

function paletteProperty(ref: ColorRef): string {
  return `${palettePrefix}${ref.replace(".", "-")}`;
}

function semanticProperty(name: string): string {
  return `${semanticPrefix}${name}`;
}

/**
 * Layer 1 as --palette-<scale>-<step> custom properties: hex values on the
 * color scales, and references to them on the role scales.
 */
export function paletteCss(): string {
  const colorLines = colorScaleNames.flatMap((name) =>
    steps.map(
      (step) =>
        `  ${paletteProperty(`${name}.${step}`)}: ${palette.scales[name][step]};`
    )
  );
  const roleLines = roleScaleNames.flatMap((name) =>
    steps.map(
      (step) =>
        `  ${paletteProperty(`${name}.${step}`)}: var(${paletteProperty(`${roleBindings[name]}.${step}`)});`
    )
  );
  const lines = [...colorLines, ...roleLines];
  lines.push(`  ${paletteProperty("white")}: ${palette.white};`);
  lines.push(`  ${paletteProperty("black")}: ${palette.black};`);
  return `${banner}\n:root {\n${lines.join("\n")}\n}\n`;
}

/**
 * Layer 2 as --color-<token> custom properties. light-dark() picks a side by
 * color-scheme: leave "light dark" to follow the system, or set "dark" or
 * "light" (on :root or any element) to pin a theme.
 */
export function semanticCss(): string {
  const lines = Object.entries(semanticTokens).map(
    ([name, { dark, light }]) =>
      `  ${semanticProperty(name)}: light-dark(var(${paletteProperty(light)}), var(${paletteProperty(dark)}));`
  );
  return `${banner}\n:root {\n  color-scheme: light dark;\n${lines.join("\n")}\n}\n`;
}

export function indexCss(): string {
  return `${banner}\n@import "./${outputFiles.palette}";\n@import "./${outputFiles.semantic}";\n`;
}

export interface ResolvedToken {
  dark: string;
  darkRef: ColorRef;
  description: string;
  light: string;
  lightRef: ColorRef;
}

export interface TokensJson {
  palette: Record<ScaleName, Scale> & { black: string; white: string };
  semantic: Record<SemanticTokenName, ResolvedToken>;
}

/** Every token resolved to #rrggbb, for code that can't read CSS. */
export function tokensJson(): TokensJson {
  const semantic = Object.fromEntries(
    Object.entries(semanticTokens).map(
      ([name, { dark, description, light }]) => [
        name,
        {
          dark: resolve(dark),
          darkRef: dark,
          description,
          light: resolve(light),
          lightRef: light
        }
      ]
    )
  ) as Record<SemanticTokenName, ResolvedToken>;
  return {
    palette: { ...palette.scales, black: palette.black, white: palette.white },
    semantic
  };
}
