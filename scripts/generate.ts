import { fromRoot, generatedDir, jsonIndent } from "./project.ts";
import { mkdirSync, writeFileSync } from "node:fs";
import { generateScales } from "./scale-generator.ts";

// Git-ignored: test, typecheck and build regenerate it before they run
const target = new URL("scales.ts", generatedDir);

mkdirSync(generatedDir, { recursive: true });
writeFileSync(
  target,
  `// Generated by pnpm generate from scripts/scale-specs.ts. Do not edit by hand.

export const scales = ${JSON.stringify(generateScales(), null, jsonIndent)} as const;
`
);
console.log(`Wrote ${fromRoot(target)}`);
